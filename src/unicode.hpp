// unicode.hpp -- the few facts about Unicode the vocabulary needs,
// as tables generated from the Unicode Character Database files
// themselves, not from whatever a language runtime bundles, which
// lags releases.  Unicode 17.0.0.
//
//   python3 - <<'EOF'
//   U = '/usr/share/unicode/'
//   cat = {}; first = None
//   for line in open(U + 'UnicodeData.txt'):
//       f = line.split(';'); cp = int(f[0], 16)
//       if f[1].endswith(', First>'): first = cp; continue
//       if f[1].endswith(', Last>'):
//           for c in range(first, cp + 1): cat[c] = f[2]
//           continue
//       cat[cp] = f[2]
//   def ranges(hit):
//       r = []; s = None
//       for c in range(0x80, 0x110000):
//           b = hit(c)
//           if b and s is None: s = c
//           if not b and s is not None: r.append((s, c - 1)); s = None
//       return r
//   marks = ranges(lambda c: cat.get(c, 'Cn')[0] in 'PZS')
//   script = {}
//   for line in open(U + 'Scripts.txt'):
//       line = line.split('#')[0].strip()
//       if not line: continue
//       rng, sc = [x.strip() for x in line.split(';')]
//       a, _, b = rng.partition('..')
//       for c in range(int(a, 16), int(b or a, 16) + 1): script[c] = sc
//   unspaced = {'Han', 'Hiragana', 'Katakana', 'Bopomofo', 'Thai',
//               'Lao', 'Khmer', 'Myanmar'}
//   short = {'Hani', 'Hira', 'Kana', 'Bopo', 'Thai', 'Laoo', 'Khmr',
//            'Mymr'}
//   for line in open(U + 'ScriptExtensions.txt'):
//       line = line.split('#')[0].strip()
//       if not line: continue
//       rng, scx = [x.strip() for x in line.split(';')]
//       if not set(scx.split()) <= short: continue
//       a, _, b = rng.partition('..')
//       for c in range(int(a, 16), int(b or a, 16) + 1): script[c] = 'Han'
//   runs_of = ranges(lambda c: script.get(c) in unspaced)
//   joining = ranges(lambda c: script.get(c) in unspaced
//                    and cat.get(c, 'Cn')[0] == 'M')
//   folds = []
//   for line in open(U + 'CaseFolding.txt'):
//       line = line.split('#')[0].strip()
